                        re_wdata_b = q_re_new;
                        re_we_a    = 1'b1;
                        re_we_b    = 1'b1;
                        im_addr_a  = addr_p_r;
                        im_addr_b  = addr_q_r;
                        im_wdata_a = p_im_new;
                        im_wdata_b = q_im_new;
                        im_we_a    = 1'b1;
                        im_we_b    = 1'b1;
                    end
                    default: ;
                endcase
            end

            S_MAGNITUDE: begin
                re_addr_a = mag_count;
                im_addr_a = mag_count;
            end

            default: ;
        endcase
    end

    // ======================================================================
    // Main state machine
    // ======================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state        <= S_COLLECT;
            sample_count <= 8'd0;
            bfly_stage   <= 3'd0;
            bfly_idx     <= 7'd0;
            bfly_step    <= 2'd0;
            mag_count    <= 8'd0;
            mag_step     <= 1'b0;
            mag_valid    <= 1'b0;
            mag_addr     <= 8'd0;
            mag_data     <= 9'd0;
        end else if(!enable)begin
            state<=S_COLLECT;sample_count<=0;bfly_step<=0;mag_step<=0;mag_valid<=0;
        end else begin
            mag_valid <= 1'b0;  // Default: no output

            case (state)
                // ----------------------------------------------------------
                // COLLECT: Store 512 incoming samples at bit-reversed addresses
                // Writes are driven by the combinational mux above.
                // ----------------------------------------------------------
                S_COLLECT: begin
                    if (sample_valid) begin
                        if (sample_count == 9'd511) begin
                            sample_count <= 8'd0;
                            bfly_stage   <= 3'd0;
                            bfly_idx     <= 7'd0;
                            bfly_step    <= 2'd0;
                            state        <= S_COMPUTE;
                        end else begin
                            sample_count <= sample_count + 8'd1;
                        end
                    end
                end

                // ----------------------------------------------------------
                // COMPUTE: 9 stages x 256 butterflies x 4 cycles each
                // Step 0: present addresses (RAM reads on next posedge)
                // Step 1: latch registered read data + twiddle
                // Step 2: write butterfly results (via mux), advance
                // ----------------------------------------------------------
                S_COMPUTE: begin
                    case (bfly_step)
                        2'd0: begin
                            // Addresses driven by mux; latch for write-back
                            addr_p_r  <= addr_p_calc;
                            addr_q_r  <= addr_q_calc;
                            bfly_step <= 2'd1;
                        end
                        2'd1: begin
                            // Registered reads are now valid; latch into butterfly regs
                            a_re     <= $signed(re_rdata_a);
                            a_im     <= $signed(im_rdata_a);
                            b_re     <= $signed(re_rdata_b);
                            b_im     <= $signed(im_rdata_b);
                            tw_cos_r <= $signed(tw_rdata[31:16]);
                            tw_sin_r <= $signed(tw_rdata[15:0]);
                            bfly_step <= 2'd2;
                        end
                        2'd2: begin
                            mul0<=tw_cos_r*b_re;mul1<=tw_sin_r*b_im;
                            mul2<=tw_cos_r*b_im;mul3<=tw_sin_r*b_re;
                            bfly_step<=2'd3;
                        end
                        2'd3: begin
                            // Writes driven by mux; advance to next butterfly
                            bfly_step <= 2'd0;
                            if (bfly_idx == 8'd255) begin
                                bfly_idx <= 7'd0;
                                if (bfly_stage == 4'd8) begin
                                    mag_count <= 8'd0;
                                    mag_step  <= 1'b0;
                                    state     <= S_MAGNITUDE;
                                end else begin
                                    bfly_stage <= bfly_stage + 3'd1;
                                end
                            end else begin
                                bfly_idx <= bfly_idx + 7'd1;
                            end
                        end
                        default: bfly_step <= 2'd0;
                    endcase
                end

                // ----------------------------------------------------------
                // MAGNITUDE: Compute |FFT[k]| for each bin, output to display
                // Step 0: present address (RAM read on next posedge)
                // Step 1: registered data valid → compute + output magnitude
                // ----------------------------------------------------------
                S_MAGNITUDE: begin
                    case (mag_step)
                        1'b0: begin
                            // Address driven by mux; save index for output
                            mag_count_d <= mag_count;
                            mag_step    <= 1'b1;
                        end
                        1'b1: begin
                            // Registered reads valid → compute magnitude combinationally
                            mag_addr  <= mag_count_d;
                            mag_data  <= magnitude;
                            mag_valid <= 1'b1;
                            mag_step  <= 1'b0;
                            if (mag_count == 9'd511) begin
                                mag_count <= 8'd0;
                                state     <= S_COLLECT;
                            end else begin
                                mag_count <= mag_count + 8'd1;
                            end
                        end
                    endcase
                end

                default: state <= S_COLLECT;
            endcase
        end
    end

endmodule
