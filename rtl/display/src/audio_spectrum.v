    // Edges: 1,2,3,4,5,7,10,14,20,28,40,57,80,113,160,208,256.
    function [3:0] band_for;
        input [7:0] k;
        begin
            if(k<2)band_for=0;else if(k<3)band_for=1;
            else if(k<4)band_for=2;else if(k<5)band_for=3;
            else if(k<7)band_for=4;else if(k<10)band_for=5;
            else if(k<14)band_for=6;else if(k<20)band_for=7;
            else if(k<28)band_for=8;else if(k<40)band_for=9;
            else if(k<57)band_for=10;else if(k<80)band_for=11;
            else if(k<113)band_for=12;else if(k<160)band_for=13;
            else if(k<208)band_for=14;else band_for=15;
        end
    endfunction
    // Approximate log2 with 3 fractional bits. Noise floor=16 FFT units;
    // full-scale Hann-windowed sinusoid ~8192 units maps to 72 pixels.
    function [6:0] log_height;
        input [15:0] magnitude;
        integer b,highest;
        reg [18:0] normalized;
        reg [7:0] log_q3;
        begin
            highest=0;
            for(b=0;b<16;b=b+1)if(magnitude[b])highest=b;
            normalized={magnitude,3'b000}>>highest;
            log_q3=(highest<<3)+normalized[2:0];
            if(magnitude<=16)log_height=0;
            else if(log_q3>=104)log_height=72;
            else log_height=log_q3-32;
        end
    endfunction
    reg [15:0] band_max[0:15];
    wire [3:0] selected_band=band_for(mag_addr[7:0]);
    integer i;
    always @(posedge clk or negedge rst_n)begin
        if(!rst_n)begin levels<=0;update<=0;for(i=0;i<16;i=i+1)band_max[i]<=0;end
        else if(!enable)begin levels<=0;update<=0;for(i=0;i<16;i=i+1)band_max[i]<=0;end
        else begin
            update<=0;
            if(mag_valid)begin
                if(mag_addr==0)for(i=0;i<16;i=i+1)band_max[i]<=0;
                else if(mag_addr<256 && mag_data>band_max[selected_band])band_max[selected_band]<=mag_data;
                if(mag_addr==511)begin
                    for(i=0;i<16;i=i+1)levels[i*7+:7]<=log_height(band_max[i]);
                    update<=1;
                end
            end
        end
    end
endmodule
