#!/usr/bin/env python3
"""Generate rtl/display/src/logo_rom.v from a 64x64 24-bit BMP.

Usage:
    python gen_logo_rom.py --placeholder logo_rom.v
    python gen_logo_rom.py --bmp my_logo.bmp logo_rom.v
    python gen_logo_rom.py --bmp my_logo.bmp --tolerance 12 logo_rom.v
    python gen_logo_rom.py --bmp my_logo.bmp --key FFFFFF logo_rom.v

The BMP must be 64x64, 24 bpp, BI_RGB (bottom-up or top-down).  The colour of
the top-left pixel is the default transparent key; every pixel equal to the key
is NOT drawn.  --key RRGGBB overrides the key, --tolerance N also treats pixels
within +-N of the key on every channel as transparent (useful for a noisy white
background that is not exactly one colour).

The generated logo_rom exports its key colour on a port, so logo_overlay always
uses the same key that was used at generation time.
"""

import struct
import sys

W, H = 64, 64


def read_bmp(path):
    data = open(path, 'rb').read()
    if data[:2] != b'BM':
        raise SystemExit('not a BMP file')
    off = struct.unpack_from('<I', data, 10)[0]
    dib = struct.unpack_from('<I', data, 14)[0]
    w, h = struct.unpack_from('<ii', data, 18)
    bpp = struct.unpack_from('<H', data, 28)[0]
    comp = struct.unpack_from('<I', data, 30)[0]
    if dib < 40 or w != W or abs(h) != H or bpp != 24 or comp != 0:
        raise SystemExit('need %dx%d 24-bit BI_RGB BMP, got %dx%d %dbpp comp=%d'
                         % (W, H, w, h, bpp, comp))
    top_down = h < 0
    stride = (w * 3 + 3) & ~3
    px = [[None] * W for _ in range(H)]
    for y in range(H):
        row = y if top_down else (H - 1 - y)
        base = off + row * stride
        for x in range(W):
            b, g, r = data[base + x * 3: base + x * 3 + 3]
            px[y][x] = (r << 16) | (g << 8) | b
    return px


def placeholder():
    px = [[0xFFFFFF] * W for _ in range(H)]

    def put(x, y, c):
        if 0 <= x < W and 0 <= y < H:
            px[y][x] = c

    fill, border = 0x1B2A4A, 0x4A6FA5
    x0, y0, x1, y1, rad = 2, 2, 61, 61, 8
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            cx = min(max(x, x0 + rad), x1 - rad)
            cy = min(max(y, y0 + rad), y1 - rad)
            if (x - cx) ** 2 + (y - cy) ** 2 > rad * rad:
                continue
            edge = (x in (x0, x1) or y in (y0, y1) or
                    ((x - cx) ** 2 + (y - cy) ** 2 >= (rad - 1) ** 2 and
                     (x in (x0, x1) or y in (y0, y1))))
            put(x, y, border if edge else fill)

    glyphs = {
        'M': ['10001', '11011', '10101', '10101', '10001', '10001', '10001'],
        'A': ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
        'L': ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
    }
    text, scale = 'MALL', 2
    tw = len(text) * 5 * scale
    tx = (W - tw) // 2
    ty = (H - 7 * scale) // 2
    color = 0xE8E8E8
    for i, ch in enumerate(text):
        rows = glyphs[ch]
        for gy, bits in enumerate(rows):
            for gx, b in enumerate(bits):
                if b == '1':
                    for dy in range(scale):
                        for dx in range(scale):
                            put(tx + i * 5 * scale + gx * scale + dx,
                                ty + gy * scale + dy, color)
    return px


def apply_key(px, key, tolerance):
    """Snap every pixel within tolerance of the key to the exact key colour."""
    if tolerance <= 0:
        return
    kr, kg, kb = (key >> 16) & 255, (key >> 8) & 255, key & 255
    for y in range(H):
        for x in range(W):
            c = px[y][x]
            if (abs(((c >> 16) & 255) - kr) <= tolerance and
                    abs(((c >> 8) & 255) - kg) <= tolerance and
                    abs((c & 255) - kb) <= tolerance):
                px[y][x] = key


def emit(px, key, path):
    lines = []
    for y in range(H):
        for x in range(W):
            c = px[y][x]
            if c != key:
                lines.append('        mem[%d] = 24\'h%06X;' % (y * W + x, c))
    out = []
    out.append('// Generated by tools/gen_logo_rom.py - do not edit by hand.')
    out.append('// %dx%d 24-bit logo, transparent key 24\'h%06X.' % (W, H, key))
    out.append('module logo_rom (')
    out.append('    input  wire        clk,')
    out.append('    input  wire [%d:0] addr,' % (len(bin(W * H - 1)) - 3))
    out.append('    output reg  [23:0] data,')
    out.append('    output wire [23:0] key')
    out.append(');')
    out.append('    reg [23:0] mem [0:%d];' % (W * H - 1))
    out.append('    integer i;')
    out.append('    initial begin')
    out.append('        for (i = 0; i < %d; i = i + 1) mem[i] = 24\'h%06X;'
               % (W * H, key))
    out.extend(lines)
    out.append('    end')
    out.append('    assign key = 24\'h%06X;' % key)
    out.append('    always @(posedge clk) data <= mem[addr];')
    out.append('endmodule')
    open(path, 'w', encoding='ascii').write('\n'.join(out) + '\n')
    print('%s: %d opaque pixels, key %06X' % (path, len(lines), key))


def main():
    args = sys.argv[1:]
    if not args:
        raise SystemExit(__doc__)
    if args[0] == '--placeholder':
        emit(placeholder(), 0xFFFFFF, args[1])
        return
    if args[0] == '--bmp':
        px = read_bmp(args[1])
        key = px[0][0]
        tol = 0
        if '--key' in args:
            key = int(args[args.index('--key') + 1], 16)
        if '--tolerance' in args:
            tol = int(args[args.index('--tolerance') + 1])
        apply_key(px, key, tol)
        emit(px, key, args[-1])
        return
    raise SystemExit(__doc__)


if __name__ == '__main__':
    main()
